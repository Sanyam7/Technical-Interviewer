package com.techinterviewer.resume.domain;

/** What a résumé experience is. */
public enum ExperienceKind {
    /** Something the candidate built: a product, a service, a side project. */
    PROJECT,
    /** What the candidate did or was in charge of in a role. */
    RESPONSIBILITY,
    /** A result the candidate claims: an improvement, a launch, a measurable outcome. */
    ACHIEVEMENT
}
