package com.techinterviewer.rag.domain;

import com.techinterviewer.common.persistence.BaseEntity;
import com.techinterviewer.common.validation.Require;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.Collections;
import java.util.Map;
import java.util.UUID;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import org.jspecify.annotations.Nullable;

/**
 * A passage of a {@link KnowledgeDocument} (table {@code knowledge_chunks}), the unit of retrieval. Written once and
 * replaced as a whole when its document is re-chunked; it never changes. The full-text vector
 * ({@code content_tsv}, generated by the database) and the embeddings belong to the AI layer and are not mapped.
 */
@Entity
@Table(name = "knowledge_chunks")
public class KnowledgeChunk extends BaseEntity {

    public static final int MAX_HEADING_PATH_LENGTH = 500;

    @Column(name = "document_id", nullable = false, updatable = false)
    private UUID documentId;

    @Column(name = "chunk_index", nullable = false, updatable = false)
    private int chunkIndex;

    @Column(name = "heading_path", updatable = false, length = MAX_HEADING_PATH_LENGTH)
    private @Nullable String headingPath;

    @Column(name = "content", nullable = false, updatable = false, columnDefinition = "text")
    private String content;

    @Column(name = "token_count", nullable = false, updatable = false)
    private int tokenCount;

    @Column(name = "topic_id", updatable = false)
    private @Nullable Long topicId;

    @Column(name = "difficulty", updatable = false)
    @JdbcTypeCode(SqlTypes.SMALLINT)
    private @Nullable Integer difficulty;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "metadata", columnDefinition = "jsonb", nullable = false, updatable = false)
    private Map<String, String> metadata;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    protected KnowledgeChunk() {
    }

    /**
     * @param chunkIndex position in the document, from 0; unique per document
     * @param content    not blank
     * @param tokenCount not negative
     * @param topicId    the catalog topic the passage is about, if known
     * @param difficulty 1 to 5 when known
     */
    public KnowledgeChunk(
            UUID documentId,
            int chunkIndex,
            @Nullable String headingPath,
            String content,
            int tokenCount,
            @Nullable Long topicId,
            @Nullable Integer difficulty,
            Map<String, String> metadata,
            Instant now) {
        this.documentId = Require.nonNull(documentId, "documentId");
        this.chunkIndex = Require.atLeast(chunkIndex, 0, "chunkIndex");
        this.headingPath = Require.nullOrNotBlank(headingPath, "headingPath", MAX_HEADING_PATH_LENGTH);
        this.content = Require.notBlank(content, "content");
        this.tokenCount = Require.atLeast(tokenCount, 0, "tokenCount");
        if (topicId != null && topicId <= 0) {
            throw new IllegalArgumentException("topicId must be positive but was " + topicId);
        }
        this.topicId = topicId;
        this.difficulty = difficulty == null ? null : Require.between(difficulty, 1, 5, "difficulty");
        this.metadata = Map.copyOf(Require.nonNull(metadata, "metadata"));
        this.createdAt = Require.nonNull(now, "now");
    }

    public UUID getDocumentId() {
        return documentId;
    }

    public int getChunkIndex() {
        return chunkIndex;
    }

    public @Nullable String getHeadingPath() {
        return headingPath;
    }

    public String getContent() {
        return content;
    }

    public int getTokenCount() {
        return tokenCount;
    }

    public @Nullable Long getTopicId() {
        return topicId;
    }

    public @Nullable Integer getDifficulty() {
        return difficulty;
    }

    public Map<String, String> getMetadata() {
        return Collections.unmodifiableMap(metadata);
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}
