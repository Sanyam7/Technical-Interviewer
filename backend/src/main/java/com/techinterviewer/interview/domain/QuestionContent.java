package com.techinterviewer.interview.domain;

import com.techinterviewer.common.collect.Immutables;
import com.techinterviewer.common.validation.Require;
import com.techinterviewer.evaluation.domain.Criterion;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import org.jspecify.annotations.Nullable;

/**
 * What a question says and where it came from, apart from its place in the interview: the wording, the
 * server-only expectations, the rubric to judge it by and the origin of the text.
 *
 * @param prompt             what the candidate reads
 * @param details            coding or design material shown with the prompt, if any
 * @param expectedKeyPoints  what a good answer contains (server-only; never sent to the candidate), ids unique
 * @param rubricId           identifier of the rubric the answer is evaluated with
 * @param origin             how the text came to be
 * @param generationLlmCallId the model call that produced it; absent for a static question
 * @param codingProblemId    the curated problem a coding question was taken from (its tests grade the solution); absent otherwise
 * @param designProblemId    the curated problem a system design question was taken from; absent otherwise
 * @param probeCriterion     the design dimension a follow-up of a design thread probes; absent otherwise
 * @param resumeItemId       the résumé experience a technical question is anchored on (x1, x2, ...); absent otherwise
 * @param questionType       what kind of questioning question it is (AI_ARCHITECTURE.md section 2.15); a follow-up carries the type of
 *                           its thread, except a claim probe, which is about the candidate's experience. Absent outside the questioning
 *                           section and for questions asked before stages existed
 * @param templateId         the curated template of the question bank the question was written from; absent otherwise
 */
public record QuestionContent(
        String prompt,
        @Nullable QuestionDetails details,
        List<ExpectedKeyPoint> expectedKeyPoints,
        String rubricId,
        QuestionOrigin origin,
        @Nullable UUID generationLlmCallId,
        @Nullable String codingProblemId,
        @Nullable String designProblemId,
        @Nullable Criterion probeCriterion,
        @Nullable String resumeItemId,
        @Nullable QuestionType questionType,
        @Nullable String templateId) {

    public static final int MAX_PROMPT_LENGTH = 10_000;
    public static final int MAX_RUBRIC_ID_LENGTH = 40;
    public static final int MAX_KEY_POINTS = 20;
    public static final int MAX_TEMPLATE_ID_LENGTH = 60;

    public QuestionContent {
        Require.notBlank(prompt, "prompt", MAX_PROMPT_LENGTH);
        expectedKeyPoints = Immutables.list(expectedKeyPoints);
        Require.notBlank(rubricId, "rubricId", MAX_RUBRIC_ID_LENGTH);
        Require.nonNull(origin, "origin");
        if (expectedKeyPoints.size() > MAX_KEY_POINTS) {
            throw new IllegalArgumentException("expectedKeyPoints must have at most " + MAX_KEY_POINTS + " entries");
        }
        Set<String> ids = new HashSet<>();
        for (ExpectedKeyPoint keyPoint : expectedKeyPoints) {
            if (!ids.add(keyPoint.id())) {
                throw new IllegalArgumentException("expected key point id '" + keyPoint.id() + "' is used twice");
            }
        }
        if (origin == QuestionOrigin.STATIC && generationLlmCallId != null) {
            throw new IllegalArgumentException("a static question was not generated by a model call");
        }
        codingProblemId = Require.nullOrNotBlank(codingProblemId, "codingProblemId", 60);
        if (codingProblemId != null && origin != QuestionOrigin.STATIC) {
            throw new IllegalArgumentException("a question taken from the problem bank is static text");
        }
        designProblemId = Require.nullOrNotBlank(designProblemId, "designProblemId", 60);
        if (designProblemId != null && origin != QuestionOrigin.STATIC) {
            throw new IllegalArgumentException("a question taken from the design problem bank is static text");
        }
        if (codingProblemId != null && designProblemId != null) {
            throw new IllegalArgumentException("a question comes from one problem bank at most");
        }
        resumeItemId = Require.nullOrNotBlank(resumeItemId, "resumeItemId", 10);
        templateId = Require.nullOrNotBlank(templateId, "templateId", MAX_TEMPLATE_ID_LENGTH);
        if (templateId != null && questionType == null) {
            throw new IllegalArgumentException("a question written from a template has the template's question type");
        }
        if (resumeItemId != null && questionType != null && questionType != QuestionType.EXPERIENCE) {
            throw new IllegalArgumentException("a question anchored on the résumé is an EXPERIENCE question");
        }
    }

    /** Content without a question type. */
    public QuestionContent(String prompt, @Nullable QuestionDetails details, List<ExpectedKeyPoint> expectedKeyPoints, String rubricId,
            QuestionOrigin origin, @Nullable UUID generationLlmCallId, @Nullable String codingProblemId, @Nullable String designProblemId,
            @Nullable Criterion probeCriterion, @Nullable String resumeItemId) {
        this(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId, probeCriterion,
                resumeItemId, null, null);
    }

    /** Content not anchored on the résumé. */
    public QuestionContent(String prompt, @Nullable QuestionDetails details, List<ExpectedKeyPoint> expectedKeyPoints, String rubricId,
            QuestionOrigin origin, @Nullable UUID generationLlmCallId, @Nullable String codingProblemId, @Nullable String designProblemId,
            @Nullable Criterion probeCriterion) {
        this(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId, probeCriterion, null);
    }

    /** Content taken from the coding problem bank, or from no bank when {@code codingProblemId} is null. */
    public QuestionContent(String prompt, @Nullable QuestionDetails details, List<ExpectedKeyPoint> expectedKeyPoints, String rubricId,
            QuestionOrigin origin, @Nullable UUID generationLlmCallId, @Nullable String codingProblemId) {
        this(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, null, null);
    }

    /** A system design problem from the design bank. */
    public static QuestionContent designProblem(String prompt, QuestionDetails details, List<ExpectedKeyPoint> expectedKeyPoints, String rubricId,
            String designProblemId) {
        return new QuestionContent(prompt, details, expectedKeyPoints, rubricId, QuestionOrigin.STATIC, null, null, designProblemId, null);
    }

    /** The same content as the probe of {@code criterion} in a design thread. */
    public QuestionContent probing(Criterion criterion) {
        return new QuestionContent(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId,
                Require.nonNull(criterion, "criterion"), resumeItemId, questionType, templateId);
    }

    /** The same content, anchored on résumé experience {@code itemId}. */
    public QuestionContent anchoredOn(String itemId) {
        return new QuestionContent(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId,
                probeCriterion, Require.notBlank(itemId, "itemId"), questionType, templateId);
    }

    /** The same content with other expected key points (a design probe carries those of its problem). */
    public QuestionContent withKeyPoints(List<ExpectedKeyPoint> keyPoints) {
        return new QuestionContent(prompt, details, keyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId,
                probeCriterion, resumeItemId, questionType, templateId);
    }

    /** The same content as a question of {@code type}, written from template {@code template} of the question bank when it is given. */
    public QuestionContent typed(QuestionType type, @Nullable String template) {
        return new QuestionContent(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, codingProblemId, designProblemId,
                probeCriterion, resumeItemId, Require.nonNull(type, "type"), template);
    }

    /** Content that does not come from the coding problem bank. */
    public QuestionContent(String prompt, @Nullable QuestionDetails details, List<ExpectedKeyPoint> expectedKeyPoints, String rubricId,
            QuestionOrigin origin, @Nullable UUID generationLlmCallId) {
        this(prompt, details, expectedKeyPoints, rubricId, origin, generationLlmCallId, null);
    }
}
